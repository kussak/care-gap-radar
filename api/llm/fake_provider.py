"""Deterministic provider for tests and offline demos. Never calls a network."""

import re


class FakeProvider:
    model = "fake-provider"

    def __init__(self, responses: list[dict] | None = None):
        """With `responses`, return them in order (to script invalid outputs); otherwise build a
        valid brief that cites the first fact IDs found in the prompt."""
        self._responses = list(responses) if responses else None
        self.calls: list[dict] = []

    def generate_json(self, system: str, user: str, schema: dict) -> dict:
        self.calls.append({"system": system, "user": user, "schema": schema})
        if self._responses is not None:
            return self._responses.pop(0)
        ids = re.findall(r'"id": "(F\d+)"', user) or ["F1"]
        return {
            "summary": "Synthetic test brief. The patient has open care needs listed in the facts.",
            "risk_explanation": "Risk is driven by the factors listed in the facts.",
            "priority_actions": [
                {
                    "action": "Call the patient to review open care gaps.",
                    "rationale": "Open gaps are listed in the facts.",
                    "fact_ids": ids[:2],
                }
            ],
            "outreach_message": "Hi, this is your care team. We would like to check in and help "
            "you schedule a visit. Please call us back when you can.",
            "caveats": ["Generated by the fake provider for testing."],
        }
